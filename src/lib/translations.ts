const messages: Record<Locale, Messages> = { en, zh, es };

function getNested(obj: Record<string, unknown>, path: string): string | undefined {
  const keys = path.split(".");
  let current: unknown = obj;
  for (const key of keys) {
    if (current == null || typeof current !== "object") return undefined;
    current = (current as Record<string, unknown>)[key];
  }
  return typeof current === "string" ? current : undefined;
}

export function getTranslation(locale: Locale, key: string): string {
  const m = messages[locale];
  const value = getNested(m as unknown as Record<string, unknown>, key);
  if (value) return value;
  const fallback = getNested(messages.en as unknown as Record<string, unknown>, key);
  return fallback ?? key;
}

export type TranslationKey = keyof Messages | `${keyof Messages}.${string}`;
